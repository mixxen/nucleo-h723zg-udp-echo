"""Generate the isolated benchmark adapter using the same descriptor/micropb path."""

import argparse
import json
import os
from pathlib import Path
import subprocess
import tempfile
from google.protobuf import descriptor_pb2
from generate import ROOT, PROTOCOL, host_target


def generate(directory):
    profile = json.loads((PROTOCOL / "benchmark/profile.json").read_text())
    subprocess.run(
        [
            os.sys.executable,
            "-m",
            "grpc_tools.protoc",
            f"-I{PROTOCOL}",
            f"--descriptor_set_out={directory}/schema.pb",
            "--include_imports",
            str(PROTOCOL / "benchmark/benchmark.proto"),
        ],
        check=True,
    )
    files = descriptor_pb2.FileDescriptorSet.FromString(
        (directory / "schema.pb").read_bytes()
    ).file
    normal, bench = files
    messages = {m.name: m for m in bench.message_type}
    messages.update(
        {m.name: m for m in normal.message_type if m.name in ("Status", "Health")}
    )
    code = [
        "// Generated by generate_benchmark.py; do not edit.",
        "use serde::{Serialize, Deserialize};",
    ]

    def typ(name, field):
        if field.type == 9:
            return f'heapless::String<{profile["string_max_utf8_bytes"][name+"."+field.name]}>'
        if field.type == 11:
            return field.type_name.split(".")[-1]
        return {13: "u32", 14: "i32", 2: "f32", 8: "bool"}[field.type]

    def pb(name):
        return (
            (
                "super::wire::messaging_::v1_"
                if name in ("Status", "Health")
                else "super::pb"
            )
            + "::"
            + name
        )

    for name, message in messages.items():
        code += [
            "#[derive(Debug, Default, Clone, PartialEq, Serialize, Deserialize)]",
            "#[serde(deny_unknown_fields)]",
            f"pub struct {name} {{",
        ]
        for field in message.field:
            code += [
                '#[serde(default, skip_serializing_if="Option::is_none", deserialize_with="crate::present")]',
                f"pub {field.name}: Option<{typ(name, field)}>,",
            ]
        code += [
            "}",
            '#[cfg(feature="protobuf")]',
            "#[allow(unused_mut, unused_variables)]",
            f"impl {name} {{",
            f"pub fn to_pb(&self) -> {pb(name)} {{",
            f"let mut out = {pb(name)}::default();",
        ]
        for field in message.field:
            if field.type == 11:
                variant = "".join(part.title() for part in field.name.split("_"))
                code += [
                    f"if let Some(v) = &self.{field.name} {{ out.body = Some(super::pb::Envelope_::Body::{variant}(v.to_pb())); }}"
                ]
            else:
                expr = (
                    "(*v).into()"
                    if field.type == 14
                    else "v.clone()" if field.type == 9 else "*v"
                )
                code += [
                    f"if let Some(v) = &self.{field.name} {{ out.set_{field.name}({expr}); }}"
                ]
        code += [
            "out",
            "}",
            f"pub fn from_pb(input: {pb(name)}) -> Self {{",
            "let mut out = Self::default();",
        ]
        for field in message.field:
            if field.type != 11:
                expr = f"input.{field.name}" + (
                    ".map(|v| v.0)" if field.type == 14 else ""
                )
                code += [f"out.{field.name} = {expr};"]
        if name == "Envelope":
            code += ["if let Some(body) = input.body { match body {"]
            for field in message.field:
                if field.type == 11:
                    variant = "".join(part.title() for part in field.name.split("_"))
                    code += [
                        f"super::pb::Envelope_::Body::{variant}(v) => out.{field.name} = Some({typ(name,field)}::from_pb(v)),"
                    ]
            code += ["}}"]
        code += ["out", "}", "}"]
    envelope = messages["Envelope"]
    by_name = {f.name: f for f in envelope.field}
    code += [
        '#[cfg(feature="csv")]',
        "impl Envelope {",
        "pub fn csv_write(&self, out: &mut [u8]) -> Result<usize, crate::CodecError> {",
        "let mut writer = super::CsvOutput::new(out);",
    ]
    for name in profile["common_csv_columns"]:
        code += [f"writer.field(self.{name}.as_ref())?;"]
    code += ["match self.kind {"]
    for kind, body in profile["kind_body"].items():
        code += [
            f"Some({kind}) => {{ let body = self.{body}.as_ref().ok_or(crate::CodecError::Validation)?;"
        ]
        for name in profile["body_csv_columns"][body]:
            code += [f"writer.field(body.{name}.as_ref())?;"]
        code += ["let _ = body; },"]
    code += [
        "_ => return Err(crate::CodecError::Validation),",
        "}",
        "writer.finish()",
        "}",
        "pub fn csv_read(cells: &[&str]) -> Result<Self, crate::CodecError> {",
        "use crate::{cells::cell, CodecError};",
        "if cells.len() < 10 { return Err(CodecError::Decode); }",
        "let mut out = Self::default();",
    ]
    for i, name in enumerate(profile["common_csv_columns"]):
        code += [f"out.{name} = cell(cells[{i}])?;"]
    code += [
        "if matches!(out.kind, Some(5 | 15 | 21 | 22)) && out.payload.is_none() { out.payload = Some(heapless::String::new()); }",
        "match out.kind {",
    ]
    for kind, body in profile["kind_body"].items():
        columns = profile["body_csv_columns"][body]
        code += [
            f"Some({kind}) => {{ if cells.len() != {10+len(columns)} {{ return Err(CodecError::Decode); }}",
            f'out.{body} = Some({typ("Envelope",by_name[body])} {{',
        ]
        for i, name in enumerate(columns):
            code += [f"{name}: cell(cells[{10+i}])?,"]
        code += ["}); },"]
    code += ["_ => return Err(CodecError::Validation),", "}", "Ok(out)", "}", "}"]
    (directory / "benchmark_model.rs").write_text("\n".join(code) + "\n")
    # Imported descriptors are generated with their original bounded capacities.
    profile["qualified_string_max_utf8_bytes"] = {
        ".messaging.v1." + key: value
        for key, value in json.loads((PROTOCOL / "profile.json").read_text())[
            "string_max_utf8_bytes"
        ].items()
    }
    (directory / "generator_profile.json").write_text(json.dumps(profile))
    subprocess.run(
        [
            "cargo",
            "+1.90.0",
            "run",
            "--locked",
            "--quiet",
            "--manifest-path",
            str(ROOT / "tools/message-demo/generator/Cargo.toml"),
            "--target",
            host_target(),
            "--",
            str(directory / "generator_profile.json"),
            str(directory / "schema.pb"),
            str(directory / "benchmark_protobuf.rs"),
        ],
        check=True,
    )
    subprocess.run(
        [
            "rustfmt",
            "+1.90.0",
            "--edition",
            "2024",
            str(directory / "benchmark_model.rs"),
        ],
        check=True,
    )
    return {
        name: ROOT / "messaging/src/generated" / name
        for name in ("benchmark_model.rs", "benchmark_protobuf.rs")
    }


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    with tempfile.TemporaryDirectory() as temp:
        directory = Path(temp)
        for name, destination in generate(directory).items():
            data = (directory / name).read_bytes()
            if args.check:
                assert (
                    destination.read_bytes() == data
                ), f"Stale generated file: {destination}"
            else:
                destination.write_bytes(data)
